CREATE TABLE recon_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP NOT NULL,
  amount_tolerance DECIMAL(19,4) NOT NULL,
  date_tolerance_days INT NOT NULL,
  total_a INT NOT NULL,
  total_b INT NOT NULL,
  exact_matches INT NOT NULL,
  tolerance_matches INT NOT NULL,
  unmatched_a INT NOT NULL,
  unmatched_b INT NOT NULL
);
CREATE TABLE recon_break (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES recon_run(id),
  type VARCHAR(32) NOT NULL,
  status VARCHAR(16) NOT NULL,
  side VARCHAR(1),
  reference VARCHAR(128) NOT NULL,
  amount DECIMAL(19,4) NOT NULL,
  currency VARCHAR(3) NOT NULL,
  trade_date DATE NOT NULL,
  counter_reference VARCHAR(128),
  counter_amount DECIMAL(19,4),
  counter_date DATE,
  note VARCHAR(500)
);
CREATE INDEX idx_break_run ON recon_break(run_id);
CREATE INDEX idx_break_run_status ON recon_break(run_id, status);
